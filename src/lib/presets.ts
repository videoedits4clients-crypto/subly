/**
 * Built-in caption style library, organised into STYLE FAMILIES (P20.2).
 *
 * A family is a recognisable visual system, not a colour scheme: each one fixes a typographic
 * personality, a layout/position, a container treatment, an emphasis strategy and a motion
 * language, and every preset in it expresses that system. Families supersede the P5-era
 * `category` grouping (Creator/Dynamic/Highlight/Clean/…), which grouped by *use* and ended up with
 * 25 of 45 presets being "white caps + black outline + fade" at the same position.
 *
 * `family` is plain data on each preset — the renderers (preview + ASS export) never look at it or
 * at a preset id; they only ever consume the resolved SubtitleStyle/AnimationConfig. See
 * __tests__/style-family-audit.test.ts for the contract each family must keep and the pairwise
 * differentiation guard, and docs/STYLE-FAMILIES.md for the design of each family.
 *
 * Migration safety: no preset id was removed. A preset folded into another ("merged") stays in the
 * array, byte-identical, flagged `replacedBy` — it still resolves through getPreset() (templates,
 * recommendations, legacy references) but is hidden from the picker.
 */
