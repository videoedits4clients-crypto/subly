export function getPreset(id: string): SubtitlePresetDef | undefined {
  return BUILT_IN_PRESETS.find((p) => p.id === id);
}

export function presetsByFamily(family: StyleFamily): SubtitlePresetDef[] {
  return BUILT_IN_PRESETS.filter((p) => p.family === family);
}

/** Presets shown in the picker: everything except presets folded into another (`replacedBy`). */
export const PICKER_PRESETS: SubtitlePresetDef[] = BUILT_IN_PRESETS.filter((p) => !p.replacedBy);

/** Picker presets of one family, its two flagship (`representative`) styles first. */
export function pickerPresetsByFamily(family: StyleFamily): SubtitlePresetDef[] {
  const inFamily = PICKER_PRESETS.filter((p) => p.family === family);
  return [...inFamily.filter((p) => p.representative), ...inFamily.filter((p) => !p.representative)];
}
