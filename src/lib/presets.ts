export interface SubtitlePresetDef {
  id: string;
  name: string;
  description: string;
  family: StyleFamily;
  /** One of the two flagship styles that define the family's look (see the family-audit test). */
  representative?: boolean;
  /** Set on a preset that was folded into another: it stays resolvable by id but is hidden from the picker. */
  replacedBy?: string;
  style: SubtitleStyle;
  animation: AnimationConfig;
}

function s(overrides: Partial<SubtitleStyle>): SubtitleStyle {
  return { ...DEFAULT_SUBTITLE_STYLE, ...overrides };
}
function a(overrides: Partial<AnimationConfig>): AnimationConfig {
  return { ...DEFAULT_ANIMATION, ...overrides };
}

